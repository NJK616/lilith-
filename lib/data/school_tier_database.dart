/// 院校层次枚举
enum SchoolTier {
  tier985('985', '顶尖'),
  tier211('211', '重点'),
  doubleFirstClass('双一流', '双一流'),
  normal('普通本科', '普通');

  final String label;
  final String shortLabel;
  const SchoolTier(this.label, this.shortLabel);
}

/// 根据学校名称自动检测层次
SchoolTier detectSchoolTier(String schoolName) {
  final name = schoolName.trim();
  // 先精确匹配
  if (_tier985Set.contains(name) || _nameVariants(name, _tier985Set)) return SchoolTier.tier985;
  if (_tier211Set.contains(name) || _nameVariants(name, _tier211Set)) return SchoolTier.tier211;
  if (_doubleFirstClassSet.contains(name) || _nameVariants(name, _doubleFirstClassSet)) return SchoolTier.doubleFirstClass;
  return SchoolTier.normal;
}

/// 模糊匹配：用户可能输入简称
bool _nameVariants(String input, Set<String> candidates) {
  // 尝试去掉"大学""学院"等后缀匹配
  final short = input.replaceAll(RegExp(r'(大学|学院|（.*?）|\(.*?\))'), '');
  for (final c in candidates) {
    final cShort = c.replaceAll(RegExp(r'(大学|学院|（.*?）|\(.*?\))'), '');
    if (short == cShort && short.length >= 4) return true;
    // 知名简称
    if (input == nameToShort[c]) return true;
  }
  return false;
}

